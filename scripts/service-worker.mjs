// Builds sw.js: the part of the app that keeps a copy of itself on the phone so it opens without internet.
// The page (index.html) and the shared wardrobe list are always asked from the site first, so a new
// version arrives as soon as there is a connection; everything else has a unique name and is served
// from the phone's copy.
import {createHash} from 'node:crypto';
export function serviceWorkerSource(files){
 const list=[...new Set(['./',...files.filter(f=>!['sw.js','.nojekyll'].includes(f)).map(f=>'./'+f)])].sort();
 const version=createHash('sha256').update(list.join('\n')+'\n'+files.join('\n')).digest('hex').slice(0,12);
 return {version,source:`// Generated by scripts/service-worker.mjs — do not edit by hand.
const VERSION=${JSON.stringify(version)},CACHE='svoy-garderob-'+VERSION,FILES=${JSON.stringify(list)};
const FRESH=['./','./index.html','./manifest.webmanifest','./shared-wardrobe/manifest.json'].map(p=>new URL(p,self.registration.scope).href);
self.addEventListener('install',event=>{event.waitUntil(caches.open(CACHE).then(cache=>Promise.all(FILES.map(path=>cache.add(new Request(new URL(path,self.registration.scope),{cache:'reload'})).catch(()=>undefined)))).then(()=>self.skipWaiting()))});
self.addEventListener('activate',event=>{event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('svoy-garderob-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()))});
self.addEventListener('fetch',event=>{
 const request=event.request,url=new URL(request.url);
 if(request.method!=='GET'||url.origin!==location.origin||!url.href.startsWith(self.registration.scope))return;
 const page=request.mode==='navigate',fresh=page||FRESH.includes(url.origin+url.pathname);
 event.respondWith(fresh?fromNetwork(request,page):fromCache(request));
});
async function fromNetwork(request,page){
 const cache=await caches.open(CACHE);
 try{const response=await fetch(request);if(response.ok)cache.put(page?new URL('./',self.registration.scope).href:request,response.clone());return response}
 catch(error){const copy=await cache.match(page?new URL('./',self.registration.scope).href:request,{ignoreSearch:true});if(copy)return copy;throw error}
}
async function fromCache(request){
 const cache=await caches.open(CACHE),copy=await cache.match(request,{ignoreSearch:true});if(copy)return copy;
 const response=await fetch(request);if(response.ok&&response.type==='basic')cache.put(request,response.clone());return response;
}
`};
}
